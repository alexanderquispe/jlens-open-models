"""Experiment 09, analysis of wordsets.py (CPU). Writes results/<model>_checks_words.md.

  F  number words, echo or belief: at com2num positions t >= 128 of the sigma = 100 conditions, the readout of the
     decade word D ("thirty" .. "seventy", D = 3..7) regressed on [last number's hundreds digit == D] and [mu's
     hundreds digit == D] (pooled over D with a per-D intercept). b_echo vs b_mu, per lens and layer.
  G  magnitude words and uncertainty: partial correlation, across positions, of the magnitude-word readout with the
     output's log sd, within cells of (condition x bin of t) (so time and condition are held fixed); and, across
     conditions late in the stream, its slope on log sigma; and after the switch, its correlation with the output's
     sd over e in [1, 300].

    python experiments/09_beliefs/checks_words.py --model llama3.1-8b
"""
import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import MU0, MUS, RAW, SIGMA0, SIGMAS, T_BINS  # noqa: E402
from stimuli import draw  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
LENS_NAME = {"logit": "logit lens", "jlens": "J-lens", "jpp": "J++ lens"}
DEC = {"thirty": 3, "forty": 4, "fifty": 5, "sixty": 6, "seventy": 7}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--model", required=True)
    p.add_argument("--raw", default=RAW)
    p.add_argument("--out", default=HERE)
    args = p.parse_args()
    R = os.path.join(args.raw, args.model)
    info = json.load(open(os.path.join(R, "wordsets_info.json")))
    sets, lenses, L = info["sets"], info["lenses"], info["n_blocks"]
    si = {s: i for i, s in enumerate(sets)}
    rows = info["stationary_rows"]
    B = np.load(os.path.join(R, "behaviour_stationary.npz"))["out_int"]  # (N, T, 5)
    T = B.shape[1]
    mu_of = {f"m{m}_s{s:03d}": (m, s) for m in range(0, 1000, 50) for s in (10, 20, 30, 50, 80, 100, 120, 150, 200)}
    nums = {}
    for r in rows:
        m, s = mu_of[r["cond"]]
        nums.setdefault(r["cond"], draw(m, s)[:, :T])
    out = [f"# Experiment 09 · word-set checks: {args.model}", "", "Generated by checks_words.py from wordsets.py.", ""]

    # F: echo vs belief for decade words ---------------------------------------------------------------------
    sel = [i for i, r in enumerate(rows) if mu_of[r["cond"]][1] == SIGMA0 and mu_of[r["cond"]][0] in MUS]
    ts = np.arange(128, T)
    out += ["## F. Number words: the last number or the belief?", "",
            "Readout (lens log-prob, nats) of the decade word D = thirty..seventy at the comma after number t, "
            "regressed on 1[last number's hundreds digit = D] (echo) and 1[mu's hundreds digit = D] (belief), "
            "with an intercept per D, over t >= 128 of the sigma = 100 conditions. Best layers by b_mu and by b_echo, "
            "and every 4th layer.", "",
            "| lens | layer | b_echo | b_mu | n |", "|---|---|---|---|---|"]
    last_dig = np.array([nums[rows[i]["cond"]][rows[i]["seq"], ts] // 100 for i in sel])  # (n, t)
    mu_dig = np.array([mu_of[rows[i]["cond"]][0] // 100 for i in sel])[:, None] * np.ones_like(last_dig)
    for k in lenses:
        X = np.load(os.path.join(R, f"stationary_{k}_wordsets.npy"))[sel]
        res = []
        for layer in range(L):
            ys, e1, m1, dd = [], [], [], []
            for w, D in DEC.items():
                y = np.asarray(X[:, ts, layer, si[w]], dtype=np.float64)
                ys.append(y.ravel()); e1.append((last_dig == D).ravel()); m1.append((mu_dig == D).ravel())
                dd.append(np.full(y.size, D))
            y, e1, m1, dd = map(np.concatenate, (ys, e1, m1, dd))
            Xd = np.column_stack([e1, m1] + [dd == D for D in DEC.values()]).astype(float)
            beta, *_ = np.linalg.lstsq(Xd, y, rcond=None)
            res.append((layer, beta[0], beta[1], len(y)))
        best_mu = max(res, key=lambda r: r[2])[0]
        best_e = max(res, key=lambda r: r[1])[0]
        for layer, be, bm, n in res:
            if layer % 4 == 0 or layer in (best_mu, best_e, L - 1):
                tag = (" (best b_mu)" if layer == best_mu else "") + (" (best b_echo)" if layer == best_e else "")
                out.append(f"| {LENS_NAME.get(k, k)} | {layer}{tag} | {be:+.3f} | {bm:+.3f} | {n} |")
    out.append("")

    # G: magnitude words and uncertainty -----------------------------------------------------------------------
    out += ["## G. Magnitude words and the output's uncertainty", "",
            "within: partial correlation, across com2num positions (t >= 8), of the magnitude-word readout with the "
            "output's log sd, both demeaned within (condition x t bin) cells. across: slope of the readout (late, "
            "t >= 512, mu = 500) on log sigma. switch: correlation of the mean trajectory with the output's sd over "
            "e in [1, 300]. The control-word set is the reference for each.", "",
            "| lens | layer | within r: magnitude (control) | across: slope on log sigma, magnitude (control) | "
            "switch r with output sd, magnitude (control) |", "|---|---|---|---|---|"]
    ok_t = np.arange(T) >= 8
    bins = np.searchsorted(T_BINS, np.arange(T), side="right") - 1
    lsd = np.log(B[:, :, 1])
    cond_idx = np.array([sorted({r["cond"] for r in rows}).index(r["cond"]) for r in rows])
    cell = cond_idx[:, None] * 10 + bins[None, :]

    def demean(x):
        x = x[:, ok_t].astype(np.float64)
        c = cell[:, ok_t]
        flat_x, flat_c = x.ravel(), c.ravel()
        means = np.bincount(flat_c, flat_x) / np.maximum(np.bincount(flat_c), 1)
        return (flat_x - means[flat_c]).reshape(x.shape)
    y = demean(lsd).ravel()
    sig_rows = [i for i, r in enumerate(rows) if mu_of[r["cond"]][0] == MU0]
    late = np.arange(T) >= 512
    ms = json.load(open(os.path.join(R, "meta_switch.json")))
    at = ms["sequences"][0]["switch_at"]
    Bs = np.load(os.path.join(R, "behaviour_switch.npz"))["out_int"]
    es = np.arange(1, 301)
    osd = np.nanmean(Bs[:, at + es, 1], 0)
    for k in lenses:
        X = np.load(os.path.join(R, f"stationary_{k}_wordsets.npy"))
        Xs = np.load(os.path.join(R, f"switch_{k}_wordsets.npy"))
        step = max(1, L // 16)
        for layer in list(range(0, L, step)) + [L - 1]:
            cells = []
            for name in ("magnitude", "control"):
                x = demean(np.asarray(X[:, :, layer, si[name]])).ravel()
                cells.append(np.corrcoef(x, y)[0, 1])
            sl = []
            for name in ("magnitude", "control"):
                v = [np.asarray(X[i, late, layer, si[name]], dtype=np.float64).mean() for i in sig_rows]
                sg = [np.log(mu_of[rows[i]["cond"]][1]) for i in sig_rows]
                sl.append(np.polyfit(sg, v, 1)[0])
            sw = []
            for name in ("magnitude", "control"):
                tr = np.asarray(Xs[:, at + es, layer, si[name]], dtype=np.float64).mean(0)
                sw.append(np.corrcoef(tr, osd)[0, 1])
            out.append(f"| {LENS_NAME.get(k, k)} | {layer} | {cells[0]:+.3f} ({cells[1]:+.3f}) | {sl[0]:+.3f} "
                       f"({sl[1]:+.3f}) | {sw[0]:+.2f} ({sw[1]:+.2f}) |")
    out.append("")
    path = os.path.join(args.out, "results", f"{args.model}_checks_words.md")
    open(path, "w").write("\n".join(out))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
