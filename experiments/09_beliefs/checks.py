"""Experiment 09, checks on the raw outputs of run_model.py (CPU). Writes results/<model>_checks.md and
figures/<model>_outlier_locked.png.

  B  null for the switch: surprise_words.py finds the surprise words rising at the switch (OLMo-3-32B), with t up to
     23 at the best of all layers. The same statistic at pseudo-switch points of the stationary sequences (sigma =
     100; nothing changes there) gives its null distribution.
  C  single outliers: in the stationary sequences (sigma = 100), numbers with |z| > 2.5 against matched typical
     numbers (|z| < 0.5): the surprise words (specific z) at the outlier and after it, and the integer mean of each
     lens and of the output, sign-aligned, from 5 numbers before to 30 after (does it jump and decay as at the
     switch?).
  D  echo: the integer mean of each lens (com2num positions, t >= 128, the sigma = 100 conditions) regressed on mu,
     on the last number's deviation x_t - mu, and on the mean deviation of the 5 numbers before it. The output's
     own coefficients are the reference: a lens coefficient on the last number far above the output's is echo.

    python experiments/09_beliefs/checks.py --model olmo-3-32b
"""
import argparse
import json
import os
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import GROUPS, MUS, RAW, SIGMA0, band  # noqa: E402
from stimuli import draw  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
LENS_NAME = {"logit": "logit lens", "jlens": "J-lens", "jpp": "J++ lens"}
gi = {g: i for i, g in enumerate(GROUPS)}
OTHERS = [gi[g] for g in GROUPS if g not in ("control", "surprise")]


def specific(D):
    """surprise-group z minus the mean of the other non-control groups (last axis: groups)."""
    return D[..., gi["surprise"]] - D[..., OTHERS].mean(-1)


def tstat(x):
    """t over axis 0."""
    return x.mean(0) / (x.std(0, ddof=1) / np.sqrt(len(x)) + 1e-9)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--model", required=True)
    p.add_argument("--raw", default=RAW)
    p.add_argument("--out", default=HERE)
    args = p.parse_args()
    R = os.path.join(args.raw, args.model)
    info = json.load(open(os.path.join(R, "run_info.json")))
    lenses, L = info["lenses"], info["n_blocks"]
    meta = json.load(open(os.path.join(R, "meta_stationary.json")))
    T, bos = meta["T"], meta["bos"]
    seqs = meta["sequences"]
    rows_mu = [i for i, s in enumerate(seqs) if s["sigma"] == SIGMA0 and s["mu"] in MUS]
    num = lambda t: bos + 2 * t  # noqa: E731  number t
    com = lambda t: bos + 2 * t + 1  # noqa: E731  the comma after it
    out = [f"# Experiment 09 · checks: {args.model}", "", "Generated by checks.py from the raw outputs of run_model.py.", ""]

    # ------------------------------------------------------------------ B: null for the switch statistic
    out += ["## B. Null for the surprise-word rise at the switch", "",
            "Statistic (as surprise_words.py): per sequence, the surprise group's z-score change from e in [-100, -10) "
            "to the position, minus the mean change of the other groups; t over the 10 sequences; the best |t| over "
            "layers. Null: pseudo-switch points t0 in {300, 400, ..., 900} of the 9 stationary conditions with sigma "
            "= 100 (63 draws per lens), where nothing changes.", "",
            "| lens | position | switch: best t (layer) | null: median, 95th pct, max of best |t| | switch above null max? |",
            "|---|---|---|---|---|"]
    ms = json.load(open(os.path.join(R, "meta_switch.json")))
    for k in lenses:
        Xs = np.asarray(np.load(os.path.join(R, f"switch_{k}_lex.npy"), mmap_mode="r"), dtype=np.float32)
        Xt = np.load(os.path.join(R, f"stationary_{k}_lex.npy"), mmap_mode="r")
        conds = {}
        for i in rows_mu:
            conds.setdefault(seqs[i]["cond"], []).append(i)
        for name, pos_of in (("num e=0", lambda t0: [num(t0)]), ("com e=0", lambda t0: [com(t0)]),
                             ("com e=1..3", lambda t0: [com(t0 + j) for j in (1, 2, 3)])):
            def stat(X, t0):
                pre = [com(t) for t in range(t0 - 100, t0 - 10)]
                dd = X[:, pos_of(t0)].mean(1) - X[:, pre].mean(1)  # (N, L, G)
                tt = tstat(specific(dd))  # (L,)
                l = int(np.argmax(np.abs(tt)))
                return tt[l], l
            real, lr = stat(Xs, ms["sequences"][0]["switch_at"])
            null = []
            for c, idx in conds.items():
                Xc = np.asarray(Xt[idx], dtype=np.float32)
                for t0 in range(300, 1000, 100):
                    null.append(abs(stat(Xc, t0)[0]))
            null = np.array(null)
            out.append(f"| {LENS_NAME.get(k, k)} | {name} | {real:+.1f} (L{lr}) | {np.median(null):.1f}, "
                       f"{np.percentile(null, 95):.1f}, {null.max():.1f} | {'yes' if abs(real) > null.max() else 'no'} |")
        del Xs
    out.append("")

    # ------------------------------------------------------------------ C: single outliers
    B = np.load(os.path.join(R, "behaviour_stationary.npz"))
    z = {}
    for i in rows_mu:
        s = seqs[i]
        z.setdefault(s["cond"], (draw(s["mu"], SIGMA0)[:, :T] - s["mu"]) / SIGMA0)
    ev_out, ev_typ = [], []  # (row, t, sign)
    for i in rows_mu:
        s = seqs[i]
        zz = z[s["cond"]][s["seq"]]
        for t in range(128, T - 31):
            if abs(zz[t]) > 2.5 and s["mu"] + 2.5 * SIGMA0 < 990 and s["mu"] - 2.5 * SIGMA0 > 10:
                ev_out.append((i, t, np.sign(zz[t])))
            elif abs(zz[t]) < 0.5 and t % 7 == 0:
                ev_typ.append((i, t, np.sign(zz[t]) or 1.0))
    E = np.arange(-5, 31)
    out += ["## C. Single outliers in the stationary streams", "",
            f"{len(ev_out)} outliers (|z| > 2.5, t >= 128, conditions with sigma = 100 whose 2.5 sd range is inside "
            f"[10, 990]) and {len(ev_typ)} typical numbers (|z| < 0.5). Unit for the t: the outlier event; events of "
            "the same sequence index share their draws across conditions (not independent), so the t are optimistic.", ""]
    out += ["### Surprise words (specific z change vs the 20 numbers before; outlier minus typical)", "",
            "| lens | at the outlier (num) | comma after it | 1-3 numbers after |", "|---|---|---|---|"]
    fig, axs = plt.subplots(1, len(lenses) + 1, figsize=(3.6 * (len(lenses) + 1), 3.2), sharey=False)
    b = band(L)
    late = list(range(b[-1] + 1, L))
    traj = {}
    for ax, k in zip(axs, lenses):
        X = np.load(os.path.join(R, f"stationary_{k}_lex.npy"), mmap_mode="r")
        S = np.load(os.path.join(R, f"stationary_{k}_scalars.npy"), mmap_mode="r")

        def locked(ev):
            sp = {"num": [], "com": [], "after": []}
            mean_traj = []
            by_row = {}
            for i, t, sg in ev:
                by_row.setdefault(i, []).append((t, sg))
            for i, evs in by_row.items():
                x = np.asarray(X[i], dtype=np.float32)
                sc = np.asarray(S[i, :, :, 1], dtype=np.float32)
                for t, sg in evs:
                    base = x[[com(u) for u in range(t - 20, t - 1)]].mean(0)
                    sp["num"].append(specific(x[num(t)] - base))
                    sp["com"].append(specific(x[com(t)] - base))
                    sp["after"].append(specific(x[[com(t + j) for j in (1, 2, 3)]].mean(0) - base))
                    m = sc[[com(t + e) for e in E]]  # (E, L)
                    mean_traj.append(sg * (m - m[:5].mean(0)))
            return {kk: np.array(v) for kk, v in sp.items()}, np.array(mean_traj)

        so, mo = locked(ev_out)
        st, mt = locked(ev_typ)
        traj[k] = mo
        cells = []
        for kk in ("num", "com", "after"):
            diff = so[kk].mean(0) - st[kk].mean(0)  # (L,)
            se = np.sqrt(so[kk].var(0, ddof=1) / len(so[kk]) + st[kk].var(0, ddof=1) / len(st[kk])) + 1e-9
            tt = diff / se
            l = int(np.argmax(np.abs(tt)))
            cells.append(f"{diff[l]:+.2f} (t {tt[l]:+.1f}, L{l})")
        out.append(f"| {LENS_NAME.get(k, k)} | " + " | ".join(cells) + " |")
        for layers, ls, lab in ((b, "-", f"layers {b[0]}-{b[-1]}"), (late, "--", f"layers {late[0]}-{late[-1]}")):
            ax.plot(E, mo[:, :, layers].mean((0, 2)), ls, color="C3", label=f"outlier, {lab}")
            ax.plot(E, mt[:, :, layers].mean((0, 2)), ls, color="grey", label=f"typical, {lab}")
        ax.axvline(0, color="k", lw=0.5, ls=":")
        ax.set_title(f"{LENS_NAME.get(k, k)}: integer mean", fontsize=9)
        ax.set_xlabel("numbers after the event")
        ax.legend(fontsize=6)
    out.append("")
    # the output's own integer mean, locked to the same events
    oi = B["out_int"]

    def out_locked(ev):
        return np.array([sg * (oi[i, [t + e for e in E], 0] - oi[i, [t + e for e in E[:5]], 0].mean()) for i, t, sg in ev])
    oo, ot = out_locked(ev_out), out_locked(ev_typ)
    axs[-1].plot(E, oo.mean(0), color="C3", label="outlier")
    axs[-1].plot(E, ot.mean(0), color="grey", label="typical")
    axs[-1].axvline(0, color="k", lw=0.5, ls=":")
    axs[-1].set_title("model output: integer mean", fontsize=9)
    axs[-1].set_xlabel("numbers after the event")
    axs[-1].legend(fontsize=6)
    axs[0].set_ylabel("change of the integer mean, toward the outlier")
    os.makedirs(os.path.join(args.out, "figures"), exist_ok=True)
    fig.tight_layout()
    fig.savefig(os.path.join(args.out, "figures", f"{args.model}_outlier_locked.png"), dpi=130)
    plt.close(fig)
    out += ["### Integer mean after an outlier (toward the outlier, minus the 5 numbers before)", "",
            "e = 0 is the comma right after the outlier (the model predicts the next number there).", "",
            "| readout | e = 0 | e = 1 | e = 3 | e = 10 | e = 30 |", "|---|---|---|---|---|---|"]
    ix = [list(E).index(e) for e in (0, 1, 3, 10, 30)]
    out.append("| output | " + " | ".join(f"{oo.mean(0)[j]:+.1f} (typ. {ot.mean(0)[j]:+.1f})" for j in ix) + " |")
    for k in lenses:
        mo = traj[k]
        for layers, lab in ((b, f"layers {b[0]}-{b[-1]}"), (late, f"layers {late[0]}-{late[-1]}")):
            tr = mo[:, :, layers].mean((0, 2))
            out.append(f"| {LENS_NAME.get(k, k)}, {lab} | " + " | ".join(f"{tr[j]:+.1f}" for j in ix) + " |")
    out.append("")

    # ------------------------------------------------------------------ D: echo
    out += ["## D. Echo: does the lens's integer mean follow mu or the last numbers?", "",
            "Regression over com2num positions t >= 128 of the sigma = 100 conditions: integer mean = a + b_mu mu + "
            "b_last (x_t - mu) + b_prev (mean of x_{t-5..t-1} - mu). For the output, b_mu is near 1; b_last and "
            "b_prev are how much a Bayesian-ish learner moves with recent numbers. A lens with b_last far above the "
            "output's reads the last number, not the belief. mass = the lens's mean softmax mass on integers there.", "",
            "| readout | layer | mass | b_mu | b_last | b_prev | R^2 |", "|---|---|---|---|---|---|---|"]
    ts = np.arange(128, T)
    Y_mu, Y_last, Y_prev, rows = [], [], [], []
    for i in rows_mu:
        s = seqs[i]
        zz = z[s["cond"]][s["seq"]] * SIGMA0
        Y_mu.append(np.full(len(ts), s["mu"], float))
        Y_last.append(zz[ts])
        Y_prev.append(np.array([zz[t - 5: t].mean() for t in ts]))
    Xd = np.stack([np.ones(len(rows_mu) * len(ts)), np.concatenate(Y_mu) - 500, np.concatenate(Y_last),
                   np.concatenate(Y_prev)], 1)

    def fit(y):
        ok = np.isfinite(y)
        beta, *_ = np.linalg.lstsq(Xd[ok], y[ok], rcond=None)
        r2 = 1 - ((y[ok] - Xd[ok] @ beta) ** 2).mean() / y[ok].var()
        return beta, r2
    beta, r2 = fit(np.concatenate([oi[i, ts, 0] for i in rows_mu]))
    out.append(f"| output | - | 1.00 | {beta[1]:.2f} | {beta[2]:.3f} | {beta[3]:.3f} | {r2:.2f} |")
    step = max(1, L // 16)
    for k in lenses:
        S = np.load(os.path.join(R, f"stationary_{k}_scalars.npy"), mmap_mode="r")
        for layer in list(range(0, L, step)) + [L - 1]:
            y = np.concatenate([np.asarray(S[i, [com(t) for t in ts], layer, 1], dtype=np.float64) for i in rows_mu])
            mass = np.mean([np.asarray(S[i, [com(t) for t in ts], layer, 0]).mean() for i in rows_mu])
            beta, r2 = fit(y)
            out.append(f"| {LENS_NAME.get(k, k)} | {layer} | {mass:.2f} | {beta[1]:.2f} | {beta[2]:.3f} | "
                       f"{beta[3]:.3f} | {r2:.2f} |")
    out.append("")
    # ------------------------------------------------------------------ E: the switch transient vs the output's sd
    out += ["## E. After the switch: does a lens band follow the output's mean or its uncertainty?", "",
            "Over e in [1, 300] (mean of the 10 switch sequences): correlation of each lens band's integer mean with "
            "the output's integer mean and with the output's sd, and the half-life of the excess over its final level "
            "(the first e where it falls below half of its peak, measured from the last 100 numbers' level).", "",
            "| readout | r with output mean | r with output sd | peak e | half-life (numbers) |", "|---|---|---|---|---|"]
    Rs = np.load(os.path.join(R, "behaviour_switch.npz"))["out_int"]
    at = ms["sequences"][0]["switch_at"]
    es = np.arange(1, 301)
    comS = [bos + 2 * (at + e) + 1 for e in es]
    om, osd = np.nanmean(Rs[:, at + es, 0], 0), np.nanmean(Rs[:, at + es, 1], 0)
    final_all = lambda x: x[-100:].mean()  # noqa: E731

    def half_life(x):
        f = final_all(x)
        ex = x - f
        pk = int(np.argmax(np.abs(ex[:50])))
        below = np.where(np.abs(ex[pk:]) < abs(ex[pk]) / 2)[0]
        return es[pk], (int(below[0]) if len(below) else None)
    pk, hl = half_life(osd)
    out.append(f"| output sd | - | 1.00 | {pk} | {hl} |")
    pk, hl = half_life(om)
    out.append(f"| output mean | 1.00 | {np.corrcoef(om, osd)[0, 1]:.2f} | {pk} | {hl} |")
    for k in lenses:
        S = np.load(os.path.join(R, f"switch_{k}_scalars.npy"), mmap_mode="r")
        for layers, lab in ((b, f"layers {b[0]}-{b[-1]}"), (late, f"layers {late[0]}-{late[-1]}")):
            x = np.asarray(S[:, comS][..., 1], dtype=np.float64)[:, :, layers].mean((0, 2))
            pk, hl = half_life(x)
            out.append(f"| {LENS_NAME.get(k, k)}, {lab} | {np.corrcoef(x, om)[0, 1]:.2f} | {np.corrcoef(x, osd)[0, 1]:.2f} "
                       f"| {pk} | {hl} |")
    out.append("")
    path = os.path.join(args.out, "results", f"{args.model}_checks.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("\n".join(out))
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
